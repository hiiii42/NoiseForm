let lang = 'zh';

export function setLang(l) {
  lang = DICT[l] ? l : 'zh';
  if (typeof document !== 'undefined') {
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
    applyI18n();
    for (const ref of copies) {
      const entry = ref.deref();
      if (!entry) copies.delete(ref);
      else if (entry.node.isConnected) entry.update();
    }
  }
}
export const getLang = () => lang;

export function t(key, vars) {
  let s = DICT[lang][key] ?? DICT.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}

export function applyI18n(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
  for (const el of root.querySelectorAll('[data-i18n-ph]')) el.placeholder = t(el.dataset.i18nPh);
  for (const el of root.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
}

// Explicit copy getters update text/accessible labels in place, preserving input,
// selection, masks and ongoing work in dialogs. User data never passes through these.
const copies = new Set();
const copyEntries = Symbol('localized copy');
export function bindCopy(node, property, read) {
  const entries = node[copyEntries] ||= new Map();
  const previous = entries.get(property);
  if (previous) { previous.read = read; previous.update(); return; }
  const entry = { node, read, update: () => {
    const value = String(entry.read() ?? '');
    if (property === 'textContent') node.textContent = value;
    else node.setAttribute(property, value);
  } };
  entries.set(property, entry);
  copies.add(new WeakRef(entry));
  entry.update();
}
